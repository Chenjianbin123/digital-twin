"""Small Blender geometry/PBR helpers shared by the graphite ward asset builders."""
from pathlib import Path
import math

import bpy
import numpy as np
from mathutils import Vector

M = {}


def linear(hex_color):
    rgb = [int(hex_color[i:i+2], 16) / 255 for i in (1, 3, 5)]
    return tuple(c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in rgb)


def material(name, color, roughness=.55, metalness=0, emission=0):
    mat = bpy.data.materials.new('WardGraphiteV1_' + name)
    mat.use_nodes = True
    rgb = linear(color)
    mat.diffuse_color = (*rgb, 1)
    node = mat.node_tree.nodes.get('Principled BSDF')
    node.inputs['Base Color'].default_value = (*rgb, 1)
    node.inputs['Roughness'].default_value = roughness
    node.inputs['Metallic'].default_value = metalness
    if emission:
        node.inputs['Emission Color'].default_value = (*rgb, 1)
        node.inputs['Emission Strength'].default_value = emission
    M[name] = mat
    return mat


def make_materials(out):
    definitions = {
        'white': ('#dddeda', .34, 0), 'plastic': ('#cbd0d1', .43, 0),
        'wall': ('#858c8f', .77, 0), 'graphite': ('#3e484f', .56, .14),
        'dark': ('#1c252b', .56, .10), 'steel': ('#b5bdc1', .31, .72),
        'silver': ('#8a989f', .42, .53), 'rubber': ('#3b4144', .83, 0),
        'linen': ('#eeeae2', .94, 0), 'blanket': ('#6a8293', .91, 0),
        'curtain': ('#748796', .9, 0), 'sheer': ('#d1d6d6', .95, 0),
        'oak': ('#b29a77', .55, 0), 'floor': ('#838b90', .52, 0),
        'screen': ('#071b25', .44, 0), 'glass': ('#f4f8fa', .015, 0),
    }
    for name, values in definitions.items():
        material(name, *values)
    material('cyan', '#62c9d3', .38, 0, 1.4)
    material('lamp', '#fff3dc', .35, 0, 3)
    material('red', '#a43946', .4)
    material('socket', '#8e8b61', .45, .5)
    glass = M['glass'].node_tree.nodes.get('Principled BSDF')
    glass.inputs['Transmission Weight'].default_value = .96
    glass.inputs['IOR'].default_value = 1.45
    sheer = M['sheer'].node_tree.nodes.get('Principled BSDF')
    sheer.inputs['Subsurface Weight'].default_value = .08
    sheer.inputs['Transmission Weight'].default_value = .30
    rng = np.random.default_rng(9292026)
    size = 512
    y, x = np.mgrid[0:size, 0:size] / size
    noise = rng.normal(0, 1, (size, size))
    for name in ['linen', 'blanket', 'curtain', 'oak', 'floor', 'graphite', 'silver']:
        mat = M[name]
        base = np.asarray(mat.diffuse_color[:3])
        if name in {'linen', 'blanket', 'curtain'}:
            height = .4 * np.sin(x * math.tau * 110) * np.sin(y * math.tau * 110) + noise * .12
            strength = .20
        elif name == 'oak':
            height = np.sin(x * 530 + 1.5 * np.sin(y * 7) + np.sin(x * 17)) * .28 + noise * .10
            strength = .16
        elif name == 'silver':
            height = np.sin(y * 1600) * .2 + noise * .13
            strength = .12
        else:
            height = noise * .22
            strength = .14
        # These are ordinary glTF images, not Blender-only procedural nodes.
        color = np.clip(base[None, None, :] * (1 + height[:, :, None] * .10), 0, 1)
        roughness = mat.node_tree.nodes.get('Principled BSDF').inputs['Roughness'].default_value
        rough = np.clip(roughness + height * .055, .05, 1)
        gy, gx = np.gradient(height)
        normal = np.stack([-gx * .2, -gy * .2, np.ones_like(gx)], axis=-1)
        normal /= np.linalg.norm(normal, axis=-1, keepdims=True)
        nodes, links = mat.node_tree.nodes, mat.node_tree.links
        bsdf = nodes.get('Principled BSDF')
        for suffix, pixels, is_color in [('color', color, True), ('roughness', np.repeat(rough[:, :, None], 3, axis=2), False), ('normal', normal * .5 + .5, False)]:
            img = bpy.data.images.new(f'ward-graphite-{name}-{suffix}', width=size, height=size, alpha=False)
            img.colorspace_settings.name = 'sRGB' if is_color else 'Non-Color'
            rgba = np.ones((size, size, 4), dtype=np.float32)
            # Generated byte-buffer images store encoded sRGB values, unlike shader inputs.
            rgba[:, :, :3] = np.where(pixels <= .0031308, pixels * 12.92,
                                      1.055 * np.power(pixels, 1 / 2.4) - .055) if is_color else pixels
            img.pixels.foreach_set(rgba.ravel())
            img.filepath_raw = str(Path(out) / 'textures' / (img.name + '.png'))
            img.file_format = 'PNG'; img.save(); img.pack()
            tex = nodes.new('ShaderNodeTexImage'); tex.image = img
            if suffix == 'normal':
                normal_node = nodes.new('ShaderNodeNormalMap')
                normal_node.inputs['Strength'].default_value = strength
                links.new(tex.outputs['Color'], normal_node.inputs['Color'])
                links.new(normal_node.outputs['Normal'], bsdf.inputs['Normal'])
            else:
                links.new(tex.outputs['Color'], bsdf.inputs['Base Color' if is_color else 'Roughness'])


def attach(obj, material=None, parent=None):
    if material is not None:
        obj.data.materials.append(M[material] if isinstance(material, str) else material)
    if parent is not None:
        obj.parent = parent
    return obj


def empty(name, parent=None):
    obj = bpy.data.objects.new(name, None)
    bpy.context.collection.objects.link(obj)
    return attach(obj, parent=parent)


def box(name, loc, size, material, bevel=.008, parent=None):
    bpy.ops.mesh.primitive_cube_add(size=1, location=loc)
    obj = bpy.context.object; obj.name = name; obj.dimensions = size
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    attach(obj, material, parent)
    if bevel:
        mod = obj.modifiers.new('Manufactured radiused edge', 'BEVEL')
        mod.width = min(bevel, min(size) * .47); mod.segments = 4
        mod.harden_normals = True
        for poly in obj.data.polygons:
            poly.use_smooth = True
        normals = obj.modifiers.new('Weighted surface normals', 'WEIGHTED_NORMAL')
        normals.keep_sharp = True
    return obj


def cylinder(name, loc, radius, depth, material, rotation=(0, 0, 0), vertices=32, parent=None):
    bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=depth, location=loc, rotation=rotation)
    obj = bpy.context.object; obj.name = name
    attach(obj, material, parent)
    for poly in obj.data.polygons:
        poly.use_smooth = len(poly.vertices) == 4
    mod = obj.modifiers.new('Machined edge', 'BEVEL'); mod.width = min(radius * .12, .0025); mod.segments = 2
    mod = obj.modifiers.new('Weighted normals', 'WEIGHTED_NORMAL'); mod.keep_sharp = True
    return obj


def sphere(name, loc, scale, material, parent=None):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=24, ring_count=12, radius=1, location=loc)
    obj = bpy.context.object; obj.name = name; obj.scale = scale
    for poly in obj.data.polygons:
        poly.use_smooth = True
    return attach(obj, material, parent)


def mesh(name, verts, faces, material, parent=None, uvs=None, smooth=False):
    data = bpy.data.meshes.new(name)
    data.from_pydata(verts, [], faces); data.update()
    obj = bpy.data.objects.new(name, data); bpy.context.collection.objects.link(obj)
    layer = data.uv_layers.new(name='UVMap')
    if uvs:
        for loop in data.loops:
            layer.data[loop.index].uv = uvs[loop.vertex_index]
    else:
        # Custom rigid panels need real texture coordinates too; authored cloth/screen UVs win.
        for poly in data.polygons:
            dominant = max(range(3), key=lambda axis: abs(poly.normal[axis]))
            axes = [(1, 2), (0, 2), (0, 1)][dominant]
            for index in poly.loop_indices:
                co = data.vertices[data.loops[index].vertex_index].co
                layer.data[index].uv = (co[axes[0]], co[axes[1]])
    for poly in data.polygons:
        poly.use_smooth = smooth
    return attach(obj, material, parent)


def tube(name, points, radius, material, parent=None, cyclic=False):
    curve = bpy.data.curves.new(name, 'CURVE'); curve.dimensions = '3D'
    curve.bevel_depth = radius; curve.bevel_resolution = 3; curve.resolution_u = 2
    spline = curve.splines.new('POLY'); spline.points.add(len(points)-1)
    for point, value in zip(spline.points, points):
        point.co = (*value, 1)
    spline.use_cyclic_u = cyclic
    obj = bpy.data.objects.new(name, curve); bpy.context.collection.objects.link(obj)
    return attach(obj, material, parent)


def text(name, body, loc, size, material, parent=None, rotation=(math.pi/2, 0, math.pi)):
    curve = bpy.data.curves.new(name, 'FONT'); curve.body = body; curve.size = size
    curve.align_x = 'CENTER'; curve.align_y = 'CENTER'; curve.extrude = .0005
    curve.font = bpy.data.fonts.get('Microsoft YaHei') or bpy.data.fonts.load('C:/Windows/Fonts/msyh.ttc')
    obj = bpy.data.objects.new(name, curve); bpy.context.collection.objects.link(obj)
    obj.location = loc; obj.rotation_euler = rotation
    return attach(obj, material, parent)


def aim(obj, target):
    obj.rotation_euler = (Vector(target) - obj.location).to_track_quat('-Z', 'Y').to_euler()


def area_light(name, loc, target, power, size, color=(1, 1, 1), size_y=None):
    data = bpy.data.lights.new(name, 'AREA'); data.energy = power; data.color = color
    data.shape = 'RECTANGLE' if size_y else 'DISK'; data.size = size
    if size_y:
        data.size_y = size_y
    obj = bpy.data.objects.new(name, data); bpy.context.collection.objects.link(obj)
    obj.location = loc; aim(obj, target)
    # These are soft lighting proxies, not luminous panels reflected in the window.
    obj.visible_glossy = False
    obj.visible_transmission = False
    return obj
